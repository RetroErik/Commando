def build_palette():
    """Return (palette list of 256 RGB tuples, ramp index map {name: [indices]})."""
    pal = [(0, 0, 0)]
    idx = {}
    for name, ramp in RAMPS.items():
        idx[name] = []
        for c in ramp:
            if c == (0, 0, 0) and name == 'gray':
                idx[name].append(0)
                continue
            pal.append(c)
            idx[name].append(len(pal) - 1)
    assert len(pal) <= 256, len(pal)
    pal += [(0, 0, 0)] * (256 - len(pal))
    return pal, idx


PALETTE, RAMP_IDX = build_palette()


def ramp_color(name, level):
    """Index of ramp `name` at fractional/integer level (clamped)."""
    r = RAMP_IDX[name]
    i = int(round(level))
    return r[max(0, min(len(r) - 1, i))]
